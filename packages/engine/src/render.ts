import type { Explanation } from "./explain.ts";
import type { Claim } from "./schema.ts";

/** Markdown rendering of one explained step. The structured step stays the source of truth. */

const BADGE: Record<Claim["kind"], string> = {
  observed: "✓ Observed",
  inferred: "~ Inferred",
  agent_stated: "💬 Agent said",
  background: "📘 Background",
};

export const AI_NOTICE =
  "> **AI-generated from captured evidence. It can be wrong.** Each statement is labeled: **✓ Observed** (shown by the evidence), **~ Inferred** (a reasonable conclusion, not shown directly), **💬 Agent said** (the AI's own account of its reasoning, not verified), **📘 Background** (general knowledge, not a claim about this project). Evidence references like [E3] point to the captured events.";

function claimLine(c: Claim, flagged: Set<string>): string {
  const refs = c.evidence.length ? ` [${c.evidence.join(", ")}]` : "";
  const flag = flagged.has(c.text.slice(0, 80)) ? " ⚠️ *failed a check, see below*" : "";
  return `- **${BADGE[c.kind]}** — ${c.text}${refs}${flag}`;
}

export function renderStep(x: Explanation, opts: { heading?: string; eventLink?: (id: number) => string } = {}): string {
  const s = x.step;
  const flagged = new Set(x.validation.issues.filter((i) => i.severity === "error" && i.claim).map((i) => i.claim!));
  const section = (title: string, claims: Claim[]) => (claims.length ? `\n### ${title}\n\n${claims.map((c) => claimLine(c, flagged)).join("\n")}\n` : "");
  const out: string[] = [
    `${opts.heading ?? "##"} ${s.title}`,
    "",
    AI_NOTICE,
    "",
    s.summary,
    section("What happened", s.whatHappened),
    section("Why it mattered", s.whyItMattered),
    section("How it works", s.howItWorks),
    section("What changed (from captured facts)", s.whatChanged),
    section("Decisions and alternatives", s.decisions),
    section("Verification (from captured test runs)", s.verification),
  ];
  if (!s.verification.length && s.generatedBy !== "facts") out.push("\n### Verification\n\n- No test runs were captured for this work.\n");
  if (s.generatedBy === "facts") out.push("\n<sub>No model was used for this step: it changed nothing in the project, so Dena summarised the captured messages directly.</sub>\n");
  if (s.concepts.length) out.push(`\n### Concepts to understand\n\n${s.concepts.map((c) => `- **${c.term}** — ${c.explanation}`).join("\n")}\n`);
  if (s.uncertainty.length) out.push(`\n### Uncertainty\n\n${s.uncertainty.map((u) => `- ${u}`).join("\n")}\n`);
  const problems = x.validation.issues;
  if (problems.length)
    out.push(`\n### Checks\n\n${problems.map((p) => `- ${p.severity === "error" ? "⚠️" : "ℹ️"} ${p.section}${p.claim ? ` — “${p.claim}…”` : ""}: ${p.message}`).join("\n")}\n`);
  const link = opts.eventLink ?? ((id: number) => `#${id}`);
  out.push(
    `\n### Evidence\n\n${Object.entries(x.evidence)
      .map(([ref, e]) => `- **${ref}** ${e.kind}, ${e.at.slice(0, 16).replace("T", " ")} UTC — events ${e.eventIds.map(link).join(", ") || "(capture gap)"}`)
      .join("\n")}\n`,
    `\n<sub>${s.generatedBy === "facts" ? "Built from facts, no model call" : `Generated by ${x.model ?? "unknown model"}${x.costUsd ? ` · $${x.costUsd.toFixed(3)}` : ""}${x.batched ? " (shared call)" : ""}${x.attempts > 1 ? " · 1 repair" : ""}`} · ${x.validation.counts.observed} observed, ${x.validation.counts.inferred} inferred, ${x.validation.counts.agent_stated} agent-stated, ${x.validation.counts.background} background claims · ${Math.round(x.validation.citedShare * 100)}% of project claims have valid citations.</sub>\n`,
  );
  return out.join("\n");
}
